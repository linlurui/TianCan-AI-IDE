// Package autotest runs browser automation tests written as small step lists.
//
// It replaces the old Playwright-script panel, which asked users to npm-install
// Playwright plus a Chromium download before anything could run. Here the
// browser is the one already on the machine, driven through the shared pure-Go
// CDP plumbing in backend/browser (go-rod): zero installs, zero extra
// runtimes, same driver as the rest of the product.
//
// A test is an ordered list of steps (open → click → fill → assert → …),
// stored as one JSON file under <project>/.tiancan/tests/ (or the global data
// dir when no project is open) so it versions with the repo and can be edited
// by hand or generated by the agent.
package autotest

import (
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"time"

	"github.com/linlurui/tiancan-ai-ide/backend/envconfig"
)

// Step types.
const (
	StepOpen        = "open"
	StepClick       = "click"
	StepFill        = "fill"
	StepAssertText  = "assertText"
	StepAssertTitle = "assertTitle"
	StepScreenshot  = "screenshot"
	StepWait        = "wait"
)

// Step is one action in a test. Which fields matter depends on Type:
//
//	open         → URL
//	click        → Selector
//	fill         → Selector + Text
//	assertText   → Selector + Text (element text must contain Text)
//	assertTitle  → Text (page title must contain Text)
//	screenshot   → Name (optional, defaults to the step index)
//	wait         → Ms (sleep) or Selector (wait for element to appear)
type Step struct {
	Type      string `json:"type"`
	URL       string `json:"url,omitempty"`
	Selector  string `json:"selector,omitempty"`
	Text      string `json:"text,omitempty"`
	Name      string `json:"name,omitempty"`
	Ms        int    `json:"ms,omitempty"`
	TimeoutMs int    `json:"timeoutMs,omitempty"`
}

// Script is one saved browser test.
type Script struct {
	ID    string `json:"id"`
	Name  string `json:"name"`
	Steps []Step `json:"steps"`
}

// idRe keeps script ids safe as file names: no separators, no traversal.
var idRe = regexp.MustCompile(`^[A-Za-z0-9_-]{1,64}$`)

// ValidateID reports whether id can be used as a script file name.
func ValidateID(id string) bool { return idRe.MatchString(id) }

// Validate checks a script before it is saved or run.
func (s Script) Validate() error {
	if strings.TrimSpace(s.Name) == "" {
		return errors.New("测试名不能为空")
	}
	if len(s.Steps) == 0 {
		return errors.New("至少需要一个步骤")
	}
	for i, st := range s.Steps {
		if err := st.Validate(); err != nil {
			return fmt.Errorf("第 %d 步（%s）：%w", i+1, st.Type, err)
		}
	}
	return nil
}

// Validate checks one step.
func (st Step) Validate() error {
	switch st.Type {
	case StepOpen:
		if strings.TrimSpace(st.URL) == "" {
			return errors.New("缺少 URL")
		}
	case StepClick:
		if st.Selector == "" {
			return errors.New("缺少选择器")
		}
	case StepFill:
		if st.Selector == "" {
			return errors.New("缺少选择器")
		}
	case StepAssertText:
		if st.Selector == "" {
			return errors.New("缺少选择器")
		}
	case StepAssertTitle:
		if st.Text == "" {
			return errors.New("缺少期望标题")
		}
	case StepScreenshot:
		// Name optional.
	case StepWait:
		if st.Ms <= 0 && st.Selector == "" {
			return errors.New("等待需要时长(ms)或选择器")
		}
	default:
		return fmt.Errorf("未知步骤类型 %q", st.Type)
	}
	return nil
}

// ScriptsDir is where tests live for a project root (empty root = global).
func ScriptsDir(root string) string {
	if root == "" {
		return filepath.Join(envconfig.DataHome(), "autotest")
	}
	return filepath.Join(root, ".tiancan", "tests")
}

// ShotsDir is where run screenshots land.
func ShotsDir(root string) string { return filepath.Join(ScriptsDir(root), "screenshots") }

func scriptPath(root, id string) (string, error) {
	if !ValidateID(id) {
		return "", fmt.Errorf("非法测试 ID: %q", id)
	}
	return filepath.Join(ScriptsDir(root), id+".json"), nil
}

// SaveScript writes one test to disk.
func SaveScript(root string, sc Script) error {
	if err := sc.Validate(); err != nil {
		return err
	}
	p, err := scriptPath(root, sc.ID)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	data, err := json.MarshalIndent(sc, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(p, append(data, '\n'), 0o644)
}

// LoadScript reads one test back.
func LoadScript(root, id string) (Script, error) {
	var sc Script
	p, err := scriptPath(root, id)
	if err != nil {
		return sc, err
	}
	data, err := os.ReadFile(p)
	if err != nil {
		return sc, err
	}
	if err := json.Unmarshal(data, &sc); err != nil {
		return sc, fmt.Errorf("解析测试文件失败: %w", err)
	}
	return sc, nil
}

// ListScripts returns every saved test, sorted by name.
func ListScripts(root string) []Script {
	entries, err := os.ReadDir(ScriptsDir(root))
	if err != nil {
		return nil
	}
	out := []Script{}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".json") {
			continue
		}
		id := strings.TrimSuffix(e.Name(), ".json")
		sc, err := LoadScript(root, id)
		if err != nil {
			continue // 坏文件不阻塞其余测试的展示
		}
		out = append(out, sc)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

// DeleteScript removes one test file.
func DeleteScript(root, id string) error {
	p, err := scriptPath(root, id)
	if err != nil {
		return err
	}
	if err := os.Remove(p); err != nil && !os.IsNotExist(err) {
		return err
	}
	return nil
}

// DefaultTimeout is the per-step budget when a step does not set its own.
const DefaultTimeout = 15 * time.Second

// StepTimeout returns how long one step may take.
func (st Step) StepTimeout() time.Duration {
	if st.TimeoutMs > 0 {
		return time.Duration(st.TimeoutMs) * time.Millisecond
	}
	return DefaultTimeout
}
